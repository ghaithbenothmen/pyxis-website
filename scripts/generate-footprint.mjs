/**
 * Turns the Pyxis footprint map (assets/map-pyxis.png) into:
 *   - public/images/map/footprint.svg  — transparent dotted map (land, project
 *     countries, offices), one path per colour so it stays light
 *   - src/data/footprint.ts            — office and project-country points,
 *     used to draw the animated network lines
 *
 * Colour coding expected in the source image:
 *   dark red  → offices        light pink → project countries
 *   grey      → land           white      → background
 *
 * Run: node scripts/generate-footprint.mjs
 */
import sharp from "sharp";
import { writeFile } from "node:fs/promises";

const SOURCE = "assets/map-pyxis.png";
const STEP = 6; // distance between dots, in source pixels
const CLUSTER = 22; // islands closer than ~2× this distance are grouped

const COLORS = {
  land: "rgba(168,200,234,0.22)", // --primary, faint
  project: "#a8c8ea", // --primary
  office: "#ce5c26", // --brand-orange
};

const { data, info } = await sharp(SOURCE).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const { width: W, height: H } = info;

/** 0 background · 1 land · 2 project country · 3 office */
function classify(x, y) {
  const i = (y * W + x) * 4;
  const [r, g, b, a] = [data[i], data[i + 1], data[i + 2], data[i + 3]];
  if (a < 128) return 0;
  if (r > 130 && g < 90 && b < 90) return 3;
  if (r - g > 14 && r > 200) return 2;
  if (r < 238 || g < 238 || b < 238) return 1;
  return 0;
}

const classes = new Uint8Array(W * H);
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) classes[y * W + x] = classify(x, y);

// Dots: majority class in each cell, with offices and project countries winning ties
const dots = { land: [], project: [], office: [] };
for (let y = STEP / 2; y < H; y += STEP) {
  for (let x = STEP / 2; x < W; x += STEP) {
    const count = [0, 0, 0, 0];
    for (let dy = -2; dy <= 2; dy++) {
      for (let dx = -2; dx <= 2; dx++) {
        const px = Math.min(W - 1, Math.max(0, Math.round(x + dx)));
        const py = Math.min(H - 1, Math.max(0, Math.round(y + dy)));
        count[classes[py * W + px]]++;
      }
    }
    if (count[3] >= 4) dots.office.push([x, y]);
    else if (count[2] >= 8) dots.project.push([x, y]);
    else if (count[1] + count[2] + count[3] >= 10) dots.land.push([x, y]);
  }
}

const path = (points) => points.map(([x, y]) => `M${x} ${y}h0`).join("");
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" fill="none" stroke-linecap="round">
<path stroke="${COLORS.land}" stroke-width="2.6" d="${path(dots.land)}"/>
<path stroke="${COLORS.project}" stroke-width="3.4" d="${path(dots.project)}"/>
<path stroke="${COLORS.office}" stroke-width="3.8" d="${path(dots.office)}"/>
</svg>
`;
await writeFile("public/images/map/footprint.svg", svg);

// Regions: connected pixels of one class (country borders are grey, so
// neighbouring countries stay separate), then nearby small islands are merged.
function regions(cls, minPixels) {
  const label = new Int32Array(W * H).fill(-1);
  const found = [];
  for (let start = 0; start < W * H; start++) {
    if (classes[start] !== cls || label[start] !== -1) continue;
    const id = found.length;
    const acc = { n: 0, sx: 0, sy: 0 };
    const stack = [start];
    label[start] = id;
    while (stack.length) {
      const p = stack.pop();
      const x = p % W;
      const y = (p - x) / W;
      acc.n++;
      acc.sx += x;
      acc.sy += y;
      for (const q of [p - 1, p + 1, p - W, p + W]) {
        if (q < 0 || q >= W * H || label[q] !== -1 || classes[q] !== cls) continue;
        if ((q === p - 1 && x === 0) || (q === p + 1 && x === W - 1)) continue;
        label[q] = id;
        stack.push(q);
      }
    }
    found.push(acc);
  }
  let groups = found.filter((g) => g.n >= 12).map((g) => ({ ...g, x: g.sx / g.n, y: g.sy / g.n }));
  for (let merged = true; merged; ) {
    merged = false;
    outer: for (let i = 0; i < groups.length; i++) {
      for (let j = i + 1; j < groups.length; j++) {
        const [g, h] = [groups[i], groups[j]];
        const small = Math.min(g.n, h.n) < 400;
        if (small && Math.hypot(g.x - h.x, g.y - h.y) < CLUSTER * 2.2) {
          const n = g.n + h.n;
          groups[i] = { n, sx: g.sx + h.sx, sy: g.sy + h.sy, x: (g.sx + h.sx) / n, y: (g.sy + h.sy) / n };
          groups.splice(j, 1);
          merged = true;
          break outer;
        }
      }
    }
  }
  return groups
    .filter((g) => g.n >= minPixels)
    .map((g) => ({ x: Math.round(g.x), y: Math.round(g.y), size: g.n }))
    .sort((a, b) => a.x - b.x);
}

const offices = regions(3, 20);
const projects = regions(2, 60);

// Tunisia is the southern of the two offices; it is the hub for network lines
const [hub, ...otherOffices] = [...offices].sort((a, b) => b.y - a.y);

const ts = `// Generated by scripts/generate-footprint.mjs from assets/map-pyxis.png — do not edit by hand.

export type MapPoint = { x: number; y: number };

export const footprintMap = {
  src: "/images/map/footprint.svg",
  width: ${W},
  height: ${H},
} as const;

/** Headquarters (Tunis): origin of the network lines. */
export const footprintHub: MapPoint = { x: ${hub.x}, y: ${hub.y} };

/** Other offices (United Kingdom). */
export const footprintOffices: MapPoint[] = ${JSON.stringify(otherOffices.map(({ x, y }) => ({ x, y })))};

/** Centroids of project countries (neighbouring countries and islands grouped). */
export const footprintProjects: MapPoint[] = ${JSON.stringify(projects.map(({ x, y }) => ({ x, y })))};
`;
await writeFile("src/data/footprint.ts", ts);

console.log(
  `dots: ${dots.land.length} land, ${dots.project.length} project, ${dots.office.length} office`,
  `\noffices: ${JSON.stringify(offices)}`,
  `\nprojects (${projects.length}): ${JSON.stringify(projects)}`,
);
